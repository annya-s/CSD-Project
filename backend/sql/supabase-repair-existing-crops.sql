-- REPAIR for the schema reported in this conversation. Run this entire file once.
-- Stop the backend first. Old crops remain in farm_legacy.crop_entry and are not
-- automatically assigned to USERS accounts. No records are deleted.
-- Run once in Supabase SQL Editor, AFTER editing the identifiers below.
-- This does not create or replace your existing user table.
-- All changes roll back together if validation or any CREATE fails.
BEGIN;
CREATE SCHEMA IF NOT EXISTS farm;
-- Preserve the existing UUID crop table and its indexes in a separate schema.
-- Its foreign key continues to reference farm.farmer_account.
DO $preserve$
BEGIN
    IF to_regclass('farm.crop_entry') IS NULL THEN
        RAISE EXCEPTION 'Expected the existing farm.crop_entry table. No changes applied.';
    END IF;
    LOCK TABLE farm.crop_entry IN ACCESS EXCLUSIVE MODE;
    IF NOT EXISTS (
        SELECT 1 FROM pg_attribute
        WHERE attrelid = 'farm.crop_entry'::regclass
          AND attname = 'farmer_id' AND atttypid = 'uuid'::regtype
          AND NOT attisdropped
    ) THEN
        RAISE EXCEPTION 'Expected UUID crop ownership. This repair may already have run; no changes applied.';
    END IF;
    IF to_regclass('farm_legacy.crop_entry') IS NOT NULL THEN
        RAISE EXCEPTION 'farm_legacy.crop_entry already exists; it will not be overwritten.';
    END IF;
    CREATE SCHEMA IF NOT EXISTS farm_legacy;
    ALTER TABLE farm.crop_entry SET SCHEMA farm_legacy;
END;
$preserve$;
DO $setup$
DECLARE
    user_schema text := 'public';
    user_table text := 'USERS';
    id_column text := 'User_ID';
    name_column text := 'User_Name';
    email_column text := 'User_Email';
    hash_column text := 'Password_Hash';
    target regclass;
BEGIN
    target := to_regclass(format('%I.%I', user_schema, user_table));
    IF target IS NULL THEN
        RAISE EXCEPTION 'User table not found: %.%. Edit identifiers at the top of this script.', user_schema, user_table;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_attribute WHERE attrelid = target
        AND attname = id_column AND atttypid = 'bigint'::regtype AND NOT attisdropped) THEN
        RAISE EXCEPTION 'This application requires an int8 (bigint) User_ID.';
    END IF;
    -- An existing int8 PK may have no default. Add an identity generator safely.
    -- An exclusive lock prevents concurrent inserts while its starting value is set.
    EXECUTE format('LOCK TABLE %I.%I IN ACCESS EXCLUSIVE MODE', user_schema, user_table);
    IF EXISTS (SELECT 1 FROM pg_attribute WHERE attrelid = target AND attname = id_column
               AND attidentity = '' AND NOT atthasdef) THEN
        EXECUTE format('ALTER TABLE %I.%I ALTER COLUMN %I ADD GENERATED BY DEFAULT AS IDENTITY', user_schema, user_table, id_column);
        EXECUTE format('SELECT setval(pg_get_serial_sequence(%L, %L), COALESCE(MAX(%I), 0) + 1, false) FROM %I.%I',
            format('%I.%I', user_schema, user_table), id_column, id_column, user_schema, user_table);
    END IF;
    -- Check all four column names without reading password data.
    EXECUTE format('SELECT %I, %I, %I, %I FROM %I.%I LIMIT 0',
        id_column, name_column, email_column, hash_column, user_schema, user_table);
    -- Password hashes must not be exposed through Supabase's browser API.
    EXECUTE format('ALTER TABLE %I.%I ENABLE ROW LEVEL SECURITY', user_schema, user_table);
    EXECUTE format('REVOKE ALL ON TABLE %I.%I FROM anon, authenticated', user_schema, user_table);
    -- Duplicate usernames/emails must fail atomically, including concurrent registrations.
    EXECUTE format('CREATE UNIQUE INDEX dome_user_name_unique ON %I.%I (%I)', user_schema, user_table, name_column);
    EXECUTE format('CREATE UNIQUE INDEX dome_user_email_unique ON %I.%I (%I)', user_schema, user_table, email_column);
    EXECUTE format($ddl$
        CREATE TABLE farm.account_status (
            farmer_id BIGINT PRIMARY KEY REFERENCES %I.%I(%I) ON DELETE CASCADE,
            email_verified BOOLEAN NOT NULL DEFAULT FALSE
        )
    $ddl$, user_schema, user_table, id_column);
    EXECUTE format('INSERT INTO farm.account_status (farmer_id) SELECT %I FROM %I.%I', id_column, user_schema, user_table);
    EXECUTE format($ddl$
        CREATE TABLE farm.account_token (
            id UUID PRIMARY KEY,
            farmer_id BIGINT NOT NULL REFERENCES %I.%I(%I) ON DELETE CASCADE,
            purpose VARCHAR(30) NOT NULL CHECK (purpose IN ('EMAIL_VERIFY', 'PASSWORD_RESET')),
            token_hash VARCHAR(128) NOT NULL UNIQUE,
            expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
            used_at TIMESTAMP WITH TIME ZONE,
            created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
        )
    $ddl$, user_schema, user_table, id_column);
    EXECUTE format($ddl$
        CREATE TABLE farm.crop_entry (
            farmer_id BIGINT NOT NULL REFERENCES %I.%I(%I) ON DELETE CASCADE,
            crop_type VARCHAR(30) NOT NULL CHECK (crop_type IN
                ('POTATO','SUGAR_CANE','APPLE','RICE','WHEAT','MAIZE','TOMATO','CARROT','LETTUCE','SOYBEAN')),
            planted_at TIMESTAMP(0) WITH TIME ZONE NOT NULL,
            latitude NUMERIC(9,6) NOT NULL CHECK (latitude BETWEEN -90 AND 90),
            longitude NUMERIC(9,6) NOT NULL CHECK (longitude BETWEEN -180 AND 180),
            created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
            PRIMARY KEY (farmer_id, crop_type, planted_at)
        )
    $ddl$, user_schema, user_table, id_column);
END;
$setup$;
CREATE INDEX crop_entry_farmer_index ON farm.crop_entry (farmer_id, planted_at);
-- These tables are accessed only by the trusted backend database role.
ALTER TABLE farm.account_status ENABLE ROW LEVEL SECURITY;
ALTER TABLE farm.account_token ENABLE ROW LEVEL SECURITY;
ALTER TABLE farm.crop_entry ENABLE ROW LEVEL SECURITY;
COMMIT;